def fgsm_attack(image, epsilon, data_grad):
    sign_data_grad = data_grad.sign()
    perturbed_image = image + epsilon * sign_data_grad
    perturbed_image = torch.clamp(perturbed_image, -1, 1)  # keep in valid range
    return perturbed_image

epsilon = 0.1  # perturbation strength

def train_adversarial(model, loader, optimizer, criterion, device, epsilon):
    model.train()
    total_loss = 0
    for imgs, labels in loader:
        imgs, labels = imgs.to(device), labels.to(device)
        imgs.requires_grad = True

        # Forward on clean image
        outputs = model(imgs)
        loss = criterion(outputs, labels)
        model.zero_grad()
        loss.backward()

        # Generate adversarial example
        imgs_adv = fgsm_attack(imgs, epsilon, imgs.grad.data)

        # Forward on adversarial image
        outputs_adv = model(imgs_adv.detach())
        loss_adv = criterion(outputs_adv, labels)

        optimizer.zero_grad()
        loss_adv.backward()
        optimizer.step()
        total_loss += loss_adv.item()

    return total_loss / len(loader)

for epoch in range(5):
    loss = train_adversarial(model, train_loader, optimizer, criterion, device, epsilon)
    acc = test(model, test_loader, device)
    print(f"Epoch {epoch+1}: Adv Loss={loss:.4f}, Accuracy={acc:.2f}%")

