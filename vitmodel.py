transform = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize((0.5,), (0.5,))
])

train_data = datasets.CIFAR10(root='./data', train=True, download=True, transform=transform)
test_data  = datasets.CIFAR10(root='./data', train=False, download=True, transform=transform)

train_loader = DataLoader(train_data, batch_size=128, shuffle=True)
test_loader  = DataLoader(test_data, batch_size=8, shuffle=True)

import torch
import torch.nn as nn

class VisionTransformer(nn.Module):
    def __init__(self, patch_size=4, num_classes=10, dim=128, depth=2, heads=4, mlp_dim=256):
        super().__init__()
        num_patches = (32 // patch_size) ** 2  # CIFAR-10 images are 32x32
        self.patch_embed = nn.Conv2d(3, dim, kernel_size=patch_size, stride=patch_size)

        self.cls_token = nn.Parameter(torch.randn(1, 1, dim))
        self.pos_embedding = nn.Parameter(torch.randn(1, num_patches + 1, dim))
        self.dropout = nn.Dropout(0.1)

        self.transformer = nn.Sequential(*[
            nn.TransformerEncoderLayer(d_model=dim, nhead=heads, dim_feedforward=mlp_dim, batch_first=True)
            for _ in range(depth)
        ])

        self.norm = nn.LayerNorm(dim)
        self.head = nn.Linear(dim, num_classes)

    def forward(self, x):
        # x shape: [B, 3, 32, 32]
        x = self.patch_embed(x)  # shape: [B, dim, 8, 8] if patch_size=4
        x = x.flatten(2).transpose(1, 2)  # shape: [B, N, dim] where N = 8x8 = 64

        B, N, D = x.shape
        cls_token = self.cls_token.expand(B, -1, -1)  # [B, 1, dim]
        x = torch.cat((cls_token, x), dim=1)  # [B, N+1, dim]
        x = self.dropout(x + self.pos_embedding[:, :N+1, :])  # add positional embeddings

        x = self.transformer(x)
        x = self.norm(x[:, 0])  # use only the [CLS] token
        return self.head(x)

def train(model, loader, optimizer, criterion, device):
    model.train()
    total_loss = 0
    for imgs, labels in loader:
        imgs, labels = imgs.to(device), labels.to(device)
        optimizer.zero_grad()
        outputs = model(imgs)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()
        total_loss += loss.item()
    return total_loss / len(loader)

def test(model, loader, device):
    model.eval()
    correct, total = 0, 0
    with torch.no_grad():
        for imgs, labels in loader:
            imgs, labels = imgs.to(device), labels.to(device)
            outputs = model(imgs)
            _, preds = torch.max(outputs, 1)
            correct += (preds == labels).sum().item()
            total += labels.size(0)
    return 100 * correct / total

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model = VisionTransformer().to(device)
criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=1e-3)

for epoch in range(10):
    loss = train(model, train_loader, optimizer, criterion, device)
    acc = test(model, test_loader, device)
    print(f"Epoch {epoch+1}: Loss={loss:.4f}, Accuracy={acc:.2f}%")

